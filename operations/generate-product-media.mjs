import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  { root: "apps/web/public/items_pictures", urlPrefix: "items_pictures" },
  { root: "apps/web/public/items", urlPrefix: "items" },
  { root: "apps/pos/public/items_pictures", urlPrefix: "items_pictures" },
];
const generatedModule = path.join(repoRoot, "packages/contracts/src/product-media-assets.generated.ts");
const outputDirectory = path.join(repoRoot, "apps/web/public/media/products/bundled");
const supportedExtensions = new Set([".jpg", ".jpeg", ".png", ".webp"]);

function identifyImage(buffer, extension) {
  if (extension === ".jpg" || extension === ".jpeg") {
    return buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff
      ? "jpg"
      : null;
  }
  if (extension === ".png") {
    return buffer.length >= 8 && buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))
      ? "png"
      : null;
  }
  if (extension === ".webp") {
    return buffer.length >= 12 && buffer.toString("ascii", 0, 4) === "RIFF" && buffer.toString("ascii", 8, 12) === "WEBP"
      ? "webp"
      : null;
  }
  return null;
}

async function imageFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await imageFiles(filename));
    else if (entry.isFile() && supportedExtensions.has(path.extname(entry.name).toLowerCase())) files.push(filename);
  }
  return files;
}

const urls = new Map();
const assets = new Map();
for (const source of sources) {
  const absoluteRoot = path.join(repoRoot, source.root);
  for (const filename of await imageFiles(absoluteRoot)) {
    const relativeFilename = path.relative(absoluteRoot, filename).split(path.sep).join("/");
    const sourceKey = `${source.urlPrefix}/${relativeFilename}`;
    const contents = await readFile(filename);
    const extension = identifyImage(contents, path.extname(filename).toLowerCase());
    if (!extension) throw new Error(`Unsupported or invalid product image: ${path.relative(repoRoot, filename)}`);

    const digest = createHash("sha256").update(contents).digest("hex");
    const assetFilename = `${digest}.${extension}`;
    const url = `/media/products/bundled/${assetFilename}`;
    const priorUrl = urls.get(sourceKey);
    if (priorUrl && priorUrl !== url) {
      throw new Error(`Conflicting bundled product image source: ${sourceKey}`);
    }
    urls.set(sourceKey, url);
    assets.set(assetFilename, contents);
  }
}

await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });
for (const [filename, contents] of assets) {
  await writeFile(path.join(outputDirectory, filename), contents, { flag: "wx" });
}

const entries = [...urls].sort(([left], [right]) => left.localeCompare(right, "en"));
const generated = [
  "// Generated by operations/generate-product-media.mjs.",
  "// Do not edit by hand; each URL is content-addressed.",
  `export const BUNDLED_PRODUCT_IMAGE_URLS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, 2)});`,
  "",
].join("\n");
await writeFile(generatedModule, generated);
console.log(`Generated ${assets.size} unique product images from ${urls.size} public source paths.`);
